import { relative } from "node:path";
import { escapePath } from "tinyglobby";
import type { ResolvedConfig } from "../../core/schema.ts";
import type { ProjectContext } from "../../core/types.ts";
import { literal, relativePath } from "./helpers.ts";

export const contentConfigTemplate = (options: {
  context: ProjectContext;
  config: ResolvedConfig;
  excludedFiles?: string[];
}): string => {
  const { context, config } = options;
  const patterns = [
    "**/*.{md,mdx}",
    "!**/_*",
    "!**/_*/**",
    "!**/{node_modules,dist,coverage,.git,.astro,.brandtree,.brandtree-verify}/**",
    ...(options.excludedFiles ?? []).map(
      (file) =>
        `!${escapePath(relative(context.contentRoot, file).replaceAll("\\", "/"))}`,
    ),
  ];

  return `// Generated by Brandtree. Do not edit.
import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { pageMetaSchema } from 'brandtree';

export const collections = {
  docs: defineCollection({
    loader: glob({
      base: ${literal(relativePath(context.outDir, context.contentRoot))},
      pattern: ${literal(patterns)},
      generateId: ({ entry }) => entry.replaceAll('\\\\', '/'),
    }),
    schema: pageMetaSchema,
  }),
};
`;
};
